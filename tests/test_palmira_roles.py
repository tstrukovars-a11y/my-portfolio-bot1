"""Капитаны команд — не участники матчей.

Турнир командный, и двое приехали не играть. Назвать капитана
участником матчей значит соврать тем, кто купил билет ради него: в
расписании его фамилии нет ни разу.
"""

import palmira


def test_капитан_назван_капитаном():
    текст = palmira.draft("Елена Веснина")
    assert "капитан команды" in текст


def test_игрок_капитаном_не_становится():
    текст = palmira.draft("Карен Хачанов")
    assert "капитан" not in текст


def test_у_капитанов_есть_справка():
    """Их анонс выходит первым и задаёт тон остальным."""
    for name in ("Елена Веснина", "Янко Типсаревич"):
        assert palmira.FACTS.get(palmira._norm(name)), name


def test_без_справки_анонс_всё_равно_собирается():
    """Выдумывать строку о человеке ради красоты поста нельзя. Пост без
    неё просто короче, а не сломан."""
    текст = palmira.draft("Анна Пушкарева")
    assert "Анна Пушкарева" in текст
    assert palmira.WHEN in текст


def test_в_составе_нет_перепутанного_имени():
    """Была Анастасия Пушкарева, а играет Анна. Чужое имя в канале
    исправляется только новым постом."""
    assert "Анна Пушкарева" in palmira.SEED
    assert "Анастасия Пушкарева" not in palmira.SEED

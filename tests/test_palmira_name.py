"""Исправление имени в очереди Пальмиры.

Имя бот берёт из чужого поста и ошибается: рядом с фамилией оказывается
второй игрок, лишнее слово или кусок рекламы. До сих пор выбор был
между «опубликовать неверно» и «выбросить» — а человек-то заявлен, и
место в списке ему полагается.
"""

import palmira


def card_marks(i: int = 0):
    return [b.callback_data for row in palmira.card_kb(i).inline_keyboard
            for b in row]


def test_в_карточке_есть_кнопка_исправить_имя():
    """Без неё неверно распознанное имя можно только выбросить вместе с
    человеком."""
    assert "pal_name_0" in card_marks()


def test_кнопки_правки_имени_и_текста_разные():
    """Это разные действия: одно меняет, кто заявлен, другое — что о нём
    написано. Склеить их значит заставить переписывать весь анонс
    из-за одной буквы в фамилии."""
    marks = card_marks()
    assert "pal_name_0" in marks and "pal_edit_0" in marks


def test_правка_имени_переписывает_анонс():
    """Анонс начинается с имени. Исправили фамилию — текст должен
    обновиться, иначе в канал уйдёт заголовок с прежней ошибкой."""
    было = palmira.draft("Александр Бублик и Елена")
    стало = palmira.draft("Александр Бублик")

    assert "Александр Бублик и Елена" in было
    assert "Александр Бублик и Елена" not in стало
    assert "Александр Бублик" in стало


def test_состояние_правки_имени_отдельное():
    """Иначе присланное имя попало бы в обработчик текста анонса и
    заменило бы собой весь анонс."""
    assert hasattr(palmira.Adding, "fixing_name")
    assert palmira.Adding.fixing_name.state != palmira.Adding.waiting_text.state

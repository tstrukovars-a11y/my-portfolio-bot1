"""Программа в посте — вся, как на афишах.

Брать её из матчей конкурса было ошибкой: конкурс знает только те
встречи, о которых можно спросить «кто победит», то есть с известными
обеими сторонами. Их шесть из двенадцати, а в программе есть ещё
пресс-конференции, чествование и церемония закрытия.
"""

import palmira


def текст():
    return "\n".join(palmira.programme_lines())


def test_все_три_дня_на_месте():
    t = текст()
    for день in ("27 ноября", "28 ноября", "29 ноября"):
        assert день in t, день


def test_все_двенадцать_матчей_на_месте():
    """В афишах двенадцать. Потерянный матч заметят те, кто придёт к
    его времени."""
    строки = [s for _, rows in palmira.PROGRAMME for s in rows]
    матчи = [s for s in строки if " — " in s and ":" in s.split(" — ")[0]
             and not any(w in s.lower() for w in
                         ("пресс-конференц", "чествование", "церемония",
                          "одного розыгрыша"))]
    assert len(матчи) == 12, матчи


def test_нераскрытые_пары_показаны_как_есть():
    """Подставлять вместо Б.О.Д пустоту нельзя: человек решит, что матч
    отменён."""
    t = текст()
    assert "Б.О.Д" in t
    assert "будет объявлено далее" in t


def test_пост_умещается_в_одно_сообщение():
    """Telegram режет на 4096 знаках, и обрежется как раз хвост с
    призывом участвовать."""
    строки = [s for _, rows in palmira.PROGRAMME for s in rows]
    assert sum(len(s) for s in строки) < 3000


def test_не_перечисляем_того_чего_в_афише_нет():
    """Выдуманный пункт программы приведёт людей к закрытым дверям."""
    t = текст()
    assert "финал" not in t.lower()

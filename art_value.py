# art_value.py — откуда берётся цена работы.
#
# Цена без объяснения — число. С объяснением — довод. Разница видна на
# первом же вопросе «а почему столько», и на него должен быть ответ
# короче, чем пауза в разговоре.
#
# Поэтому здесь считается ориентир и сразу пишется, из чего он сложился.
# Арифметика на виду намеренно: непрозрачный расчёт убедителен ровно до
# первого недоверчивого человека, а показанный — работает и с ним.
#
# ЧЕГО ЗДЕСЬ НЕТ. Это не оценка. Оценку даёт эксперт и выдаёт
# документом; программа этого не умеет и уметь не может — ей неоткуда
# взять то, что знает эксперт. Сервисы, которые принимают фотографию и
# называют сумму, считают по истории аукционных продаж автора: у автора
# без такой истории считать не из чего, и число у них берётся из
# воздуха.
#
# Здесь считается другое и называется честно: сколько просят за работу
# такого размера и техники. Это не истина, а отправная точка разговора
# — и именно в таком виде ею пользуются площадки для начинающих.
import re

# Базовая ставка за сантиметр суммы сторон. Метод линейного сантиметра —
# то, чем пользуются сами художники: цена растёт с размером не по
# площади, а медленнее, иначе большой холст выходит неподъёмным.
BASE = 350          # ₽ за сантиметр (ширина + высота)
MATERIALS = 2500    # холст, подрамник, краски — ниже этого работать в минус

# Техника меняет и себестоимость, и то, как вещь воспринимают. Акварель
# под стеклом живёт иначе, чем масло на холсте, и стоит иначе.
TECHNIQUE = {
    "масло": 1.0, "холст_масло": 1.0, "картон_масло": 0.85,
    "акрил": 0.9, "пастель": 0.75, "акварель": 0.6, "графика": 0.55,
    "смешанная": 0.9,
}

# Что автор уже продал — главный множитель. Он и есть та самая
# статистика реализованного: пока продаж нет, цену держит только размер.
HISTORY = {
    0: (1.0, "продаж пока нет"),
    1: (1.3, "есть проданные работы"),
    5: (1.8, "продажи идут регулярно"),
    15: (2.5, "устойчивый спрос"),
}

SPREAD = 0.25       # вилка вокруг ориентира: цена — диапазон, не точка

# Заказная работа по формуле не считается. Герб рода, портрет, вещь «под
# интерьер» стоят не размером: платят за то, что этого нет ни у кого
# другого. Подставлять сюда ту же арифметику — значит занижать заказ и
# завышать всё остальное, если потом считать от него.
COMMISSION = ("герб", "портрет", "заказ", "на заказ", "под интерьер")


def _technique_key(text: str) -> str:
    low = (text or "").lower()
    for word in ("холст_масло", "картон_масло", "смешанная", "акварель",
                 "пастель", "графика", "акрил", "масло"):
        if word.replace("_", " ") in low or word in low:
            return word
    return "масло"


def is_commission(title: str, technique: str = "") -> bool:
    """Заказная ли вещь. Такую формулой не считают."""
    low = f"{title} {technique}".lower()
    return any(word in low for word in COMMISSION)


def _history_factor(sold: int):
    best = (1.0, HISTORY[0][1])
    for threshold in sorted(HISTORY):
        if sold >= threshold:
            best = HISTORY[threshold]
    return best


def estimate(width_cm: float, height_cm: float, technique: str = "",
             sold_count: int = 0) -> dict:
    """Ориентир и всё, из чего он сложился.

    Возвращаем не только число, но и слагаемые: по ним пишется
    объяснение, и по ним же видно, где расчёт ошибается.
    """
    if width_cm <= 0 or height_cm <= 0:
        return {}

    key = _technique_key(technique)
    tech_factor = TECHNIQUE.get(key, 1.0)
    hist_factor, hist_words = _history_factor(sold_count)

    linear = width_cm + height_cm
    raw = linear * BASE * tech_factor * hist_factor + MATERIALS
    middle = int(round(raw / 1000) * 1000)

    return {
        "linear": linear,
        "base": BASE,
        "technique": key,
        "technique_factor": tech_factor,
        "history_factor": hist_factor,
        "history_words": hist_words,
        "materials": MATERIALS,
        "middle": middle,
        "low": int(round(middle * (1 - SPREAD) / 1000) * 1000),
        "high": int(round(middle * (1 + SPREAD) / 1000) * 1000),
    }


def _money(value) -> str:
    return f"{int(value):,}".replace(",", " ") + " ₽"


DISCLAIMER = (
    "<i>Это не оценка. Оценку даёт эксперт и выдаёт документом. "
    "Здесь арифметика по размеру и технике — то же, чем пользуются "
    "площадки для начинающих авторов, и точка, с которой начинают "
    "разговор о цене.</i>"
)

COMMISSION_TEXT = (
    "📐 <b>Эту работу формулой не считают</b>\n\n"
    "Герб, портрет, вещь под конкретный интерьер — заказ. За него "
    "платят не за размер, а за то, чего нет ни у кого другого: "
    "родовой знак существует в одном экземпляре, и сравнивать его с "
    "пейзажем того же размера не с чем.\n\n"
    "Цена заказа складывается из трёх вещей: сколько времени заняла "
    "работа, насколько сложен сюжет и что он значит для заказчика. "
    "Третье обычно и решает.\n\n"
    "{extra}"
)


def explain(width_cm: float, height_cm: float, technique: str = "",
            sold_count: int = 0, title: str = "") -> str:
    """Ориентир словами — с показанной арифметикой.

    Арифметику показываем не из педантизма. Названное без объяснения
    число вызывает один вопрос — «почему столько», — и человек задаёт
    его не боту, а себе, и отвечает «дорого». Показанный расчёт отвечает
    раньше, чем вопрос возникнет.
    """
    if is_commission(title, technique):
        return COMMISSION_TEXT.format(extra=DISCLAIMER)

    got = estimate(width_cm, height_cm, technique, sold_count)
    if not got:
        return "Нужны размеры работы в сантиметрах."

    lines = ["📐 <b>Сколько просят за такую работу</b>", ""]
    lines.append(f"<b>{_money(got['low'])} — {_money(got['high'])}</b>")
    lines.append("")
    lines.append("<b>Из чего сложилось</b>")
    lines.append(f"{width_cm:g} + {height_cm:g} = {got['linear']:g} см "
                 f"по сумме сторон")
    lines.append(f"× {got['base']} ₽ за сантиметр")
    if got["technique_factor"] != 1.0:
        lines.append(f"× {got['technique_factor']:g} — "
                     f"{got['technique'].replace('_', ', ')}")
    if got["history_factor"] != 1.0:
        lines.append(f"× {got['history_factor']:g} — {got['history_words']}")
    lines.append(f"+ {_money(got['materials'])} материалы")
    lines.append("")
    lines.append(f"Середина: {_money(got['middle'])}")
    lines.append("")

    # Самое полезное для автора — не число, а то, что его двигает.
    if got["history_factor"] == 1.0:
        lines.append("<b>Что поднимает цену</b>\nПроданные работы. Пока "
                     "продаж нет, цену держит только размер — и это "
                     "нормально: первые работы продают, чтобы появилась "
                     "история, а не чтобы заработать.")
        lines.append("")
    lines.append(DISCLAIMER)
    return "\n".join(lines)


def parse_size(text: str):
    """«60 на 80», «60x80 см» → (60.0, 80.0). Не разобрали — (0, 0)."""
    found = re.search(
        r"(\d{1,3}(?:[.,]\d)?)\s*(?:[x×хХ*]|на)\s*(\d{1,3}(?:[.,]\d)?)",
        text or "")
    if not found:
        return 0.0, 0.0
    return (float(found.group(1).replace(",", ".")),
            float(found.group(2).replace(",", ".")))
